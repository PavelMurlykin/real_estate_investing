import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { test } from 'node:test'
import { baseUrl, createPage, screenshot } from './helpers.mjs'
import { assertCurrentLinkVisible, assertNavigationStyles } from './navigation-style-helpers.mjs'

const fixtures = JSON.parse(await readFile(new URL('./feedback-fixtures.json', import.meta.url), 'utf8'))

for (const width of [360, 768, 1280]) for (const theme of ['light', 'dark']) {
  test(`navigation style supports current routes, keyboard and history in ${theme} at ${width}px`, async (context) => {
    const page = await createPage(context, { width, height: 900 })
    await page.addInitScript((value) => localStorage.setItem('theme-preference', value), theme)
    await page.route('**/api/v1/auth/session/', (route) => route.fulfill({ json: fixtures.administrator }))
    for (const [route, label] of [['banks', 'Разделы банков'], ['locations/regions', 'Справочники локаций'], ['dictionaries/real-estate-types', 'Справочники объектов']]) {
      await page.goto(baseUrl + '/app/' + route)
      const navigation = page.getByRole('navigation', { name: label, exact: true })
      await navigation.waitFor()
      await assertNavigationStyles(page)
      await assertCurrentLinkVisible(navigation)
      const links = navigation.getByRole('link')
      const first = links.first()
      const last = links.last()
      const address = page.url()
      await first.focus()
      await page.keyboard.press('Tab')
      assert.equal(await links.nth(1).evaluate((element) => element === document.activeElement), true)
      await page.keyboard.press('Shift+Tab')
      assert.equal(await first.evaluate((element) => element === document.activeElement), true)
      await page.keyboard.press('ArrowLeft')
      assert.equal(await last.evaluate((element) => element === document.activeElement), true)
      assert.equal(page.url(), address, 'Arrow keys must only move focus')
      const outline = await last.evaluate((element) => ({ width: getComputedStyle(element).outlineWidth, style: getComputedStyle(element).outlineStyle }))
      assert.deepEqual(outline, { width: '3px', style: 'solid' })
      const target = await last.getAttribute('href')
      await page.keyboard.press('Enter')
      await page.waitForURL(new URL(target, baseUrl).href)
      await navigation.locator('a[aria-current="page"]').waitFor()
      await assertCurrentLinkVisible(navigation)
      await assertNavigationStyles(page)
      await screenshot(page, `navigation-${route.replaceAll('/', '-')}-${theme}-${width}.png`)
      await page.goBack()
      await page.waitForURL(address)
      await assertCurrentLinkVisible(navigation)
      await page.goForward()
      await page.waitForURL(new URL(target, baseUrl).href)
      await assertCurrentLinkVisible(navigation)
      await last.focus()
      await page.keyboard.press('Home')
      assert.equal(await first.evaluate((element) => element === document.activeElement), true)
      await page.keyboard.press('End')
      assert.equal(await last.evaluate((element) => element === document.activeElement), true)
      await page.keyboard.press('Tab')
      assert.equal(await navigation.evaluate((element) => element.contains(document.activeElement)), false)
    }

    await page.goto(baseUrl + '/app/mortgage/trench/calculations/17')
    const primary = page.getByRole('navigation', { name: 'Основная навигация' })
    await primary.getByRole('link', { name: 'Ипотечный калькулятор' }).and(page.locator('[aria-current="page"]')).waitFor()
    if (width <= 960) {
      const opener = page.getByRole('button', { name: 'Открыть меню разделов' })
      await opener.focus()
      await page.keyboard.press('Enter')
      const dialog = page.getByRole('dialog', { name: 'Навигация по разделам' })
      const sections = dialog.getByRole('navigation', { name: 'Разделы приложения' })
      await dialog.waitFor()
      await sections.getByRole('link', { name: 'История траншей' }).and(page.locator('[aria-current="page"]')).waitFor()
      await assertCurrentLinkVisible(sections)
      await assertNavigationStyles(page)
      await screenshot(page, `navigation-menu-${theme}-${width}.png`)
      const bank = sections.getByRole('link', { name: 'Банки', exact: true })
      const popupPromise = page.context().waitForEvent('page')
      await bank.focus()
      await bank.click({ modifiers: ['Control'] })
      const popup = await popupPromise
      await popup.waitForURL((url) => /^\/app\/banks\/?$/.test(url.pathname))
      await popup.close()
      assert.equal(await dialog.isVisible(), true, 'Opening another tab must retain the menu')
      await page.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
      assert.equal(await opener.evaluate((element) => element === document.activeElement), true)
      await opener.click()
      await bank.focus()
      await page.keyboard.press('Enter')
      await page.waitForURL((url) => /^\/app\/banks\/?$/.test(url.pathname))
      await dialog.waitFor({ state: 'hidden' })
      await page.waitForFunction(() => document.activeElement === document.querySelector('main'))
    } else {
      const sections = page.getByRole('navigation', { name: 'Разделы приложения' })
      await sections.getByRole('link', { name: 'История траншей' }).and(page.locator('[aria-current="page"]')).waitFor()
      await assertCurrentLinkVisible(sections)
      await assertNavigationStyles(page)
      await screenshot(page, `navigation-sidebar-${theme}-${width}.png`)
    }
  })
}

test('navigation style remains accessible at phone, landscape and sidebar breakpoints', async (context) => {
  const page = await createPage(context, { width: 320, height: 568 })
  await page.route('**/api/v1/auth/session/', (route) => route.fulfill({ json: fixtures.administrator }))
  for (const [width, height] of [[320, 568], [720, 480], [721, 480], [960, 600], [961, 600]]) {
    await page.setViewportSize({ width, height })
    await page.goto(baseUrl + '/app/mortgage/trench/calculations/17')
    await page.getByRole('navigation', { name: 'Основная навигация' }).waitFor()
    await assertNavigationStyles(page)
    if (width <= 960) {
      await page.getByRole('button', { name: 'Открыть меню разделов' }).click()
      const dialog = page.getByRole('dialog', { name: 'Навигация по разделам' })
      const sections = dialog.getByRole('navigation', { name: 'Разделы приложения' })
      await sections.getByRole('link', { name: 'История траншей' }).and(page.locator('[aria-current="page"]')).waitFor()
      await assertCurrentLinkVisible(sections)
      await assertNavigationStyles(page)
      await page.setViewportSize({ width: Math.min(width, 720), height: 400 })
      await assertCurrentLinkVisible(sections)
      await assertNavigationStyles(page)
      await page.setViewportSize({ width: 1280, height: 900 })
      await dialog.waitFor({ state: 'hidden' })
      assert.equal(await page.evaluate(() => document.body.style.overflow), '')
    } else assert.equal(await page.getByRole('complementary', { name: 'Навигация по разделам' }).isVisible(), true)
  }
})
